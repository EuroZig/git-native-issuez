// Package enumgen writes enums_gen.go: a String method for each of the
// binding's enum types, the integer types with a const block of their
// own values that have no String method yet. A value's string is its Go
// name without the prefix its block shares, in snake case:
// PushFastForward is "fast_forward".
package enumgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"sort"
	"strings"
	"unicode"
)

type enum struct {
	name   string
	values []string // Go names, in source order
}

// Generate writes enums_gen.go from the package's Go files (name to
// source), test files excluded.
func Generate(files map[string][]byte) ([]byte, error) {
	enums, err := collect(files)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/enumgen; DO NOT EDIT.\n\npackage issuez\n\nimport \"strconv\"\n")
	for _, e := range enums {
		prefix := commonPrefix(e.values)
		fmt.Fprintf(&b, "\n// String is the value's name, %q for %s.\n", snake(strings.TrimPrefix(e.values[0], prefix)), e.values[0])
		fmt.Fprintf(&b, "func (v %s) String() string {\n\tswitch v {\n", e.name)
		for _, v := range e.values {
			fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %q\n", v, snake(strings.TrimPrefix(v, prefix)))
		}
		fmt.Fprintf(&b, "\t}\n\treturn %q + strconv.Itoa(int(v)) + \")\"\n}\n", e.name+"(")
	}
	return format.Source(b.Bytes())
}

// collect finds the enums to generate String for, sorted by name.
func collect(files map[string][]byte) ([]*enum, error) {
	fset := token.NewFileSet()
	ints := map[string]bool{}
	stringers := map[string]bool{}
	var enums []*enum
	byName := map[string]*enum{}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if strings.HasSuffix(n, "_test.go") || strings.HasSuffix(n, "_gen.go") {
			continue
		}
		f, err := parser.ParseFile(fset, n, files[n], 0)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil && d.Name.Name == "String" {
					stringers[recvName(d.Recv.List[0].Type)] = true
				}
			case *ast.GenDecl:
				switch d.Tok {
				case token.TYPE:
					for _, s := range d.Specs {
						ts := s.(*ast.TypeSpec)
						if id, ok := ts.Type.(*ast.Ident); ok && isInt(id.Name) {
							ints[ts.Name.Name] = true
						}
					}
				case token.CONST:
					var typ string
					seen := map[string]bool{}
					for _, s := range d.Specs {
						vs := s.(*ast.ValueSpec)
						if id, ok := vs.Type.(*ast.Ident); ok {
							typ = id.Name
						} else if vs.Type == nil && len(vs.Values) > 0 {
							typ = "" // untyped
						}
						if typ == "" {
							continue
						}
						e := byName[typ]
						if e == nil {
							e = &enum{name: typ}
							byName[typ] = e
							enums = append(enums, e)
						}
						// Two names for one value: the first names it.
						key := ""
						if len(vs.Values) == 1 {
							key = exprKey(fset, vs.Values[0])
						}
						for _, id := range vs.Names {
							if key != "" && seen[key] {
								continue
							}
							if key != "" {
								seen[key] = true
							}
							e.values = append(e.values, id.Name)
						}
					}
				}
			}
		}
	}
	sort.Slice(enums, func(i, j int) bool { return enums[i].name < enums[j].name })
	var out []*enum
	for _, e := range enums {
		if ints[e.name] && !stringers[e.name] && len(e.values) >= 2 {
			out = append(out, e)
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no enums found")
	}
	return out, nil
}

// exprKey is a value's source, "" for iota.
func exprKey(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	if err := format.Node(&b, fset, e); err != nil {
		return ""
	}
	// iota counts on: each name is its own value.
	if b.String() == "iota" {
		return ""
	}
	return b.String()
}

func isInt(name string) bool {
	switch name {
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64":
		return true
	}
	return false
}

func recvName(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// commonPrefix is the leading words (from one capital to the next) every
// name shares, short of the whole of any name.
func commonPrefix(names []string) string {
	words := camelWords(names[0])
	n := len(words) - 1
	for _, name := range names[1:] {
		w := camelWords(name)
		i := 0
		for i < n && i < len(w)-1 && w[i] == words[i] {
			i++
		}
		n = i
	}
	return strings.Join(words[:n], "")
}

func camelWords(s string) []string {
	var out []string
	start := 0
	r := []rune(s)
	for i := 1; i < len(r); i++ {
		// A new word at a capital after a lower-case letter, or at the
		// last capital of a run followed by a lower-case one (IDFoo).
		if unicode.IsUpper(r[i]) && (unicode.IsLower(r[i-1]) ||
			(i+1 < len(r) && unicode.IsLower(r[i+1]))) {
			out = append(out, string(r[start:i]))
			start = i
		}
	}
	return append(out, string(r[start:]))
}

func snake(s string) string {
	return strings.ToLower(strings.Join(camelWords(s), "_"))
}
